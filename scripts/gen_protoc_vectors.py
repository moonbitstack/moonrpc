"""Write src/examples/21-annotations/protoc_wbtest.mbt: what protoc makes of
the `.proto` source the annotated example's `descriptor().source()` prints,
and how Python's protobuf runtime, built from that source, encodes the
example's messages. The example must describe itself as protoc does and
encode as Python does.

    pip install grpcio-tools
    python3 scripts/gen_protoc_vectors.py
"""

import importlib
import pathlib
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
EXAMPLE = "src/examples/21-annotations"
OUT = ROOT / EXAMPLE / "protoc_wbtest.mbt"


def source() -> str:
    run = subprocess.run(
        ["moon", "run", EXAMPLE, "--target", "native"],
        cwd=ROOT,
        check=True,
        capture_output=True,
        text=True,
    )
    lines = run.stdout.splitlines()
    start = next(i for i, line in enumerate(lines) if line.startswith("syntax = "))
    end = next(i for i in range(start, len(lines)) if lines[i] == "generated and hand-written services agree")
    return "\n".join(lines[start:end]).rstrip() + "\n"


def main() -> None:
    with tempfile.TemporaryDirectory() as tmp:
        work = pathlib.Path(tmp)
        (work / "greeter.proto").write_text(source(), encoding="utf-8")
        subprocess.run(
            [
                sys.executable, "-m", "grpc_tools.protoc", f"-I{work}",
                f"--descriptor_set_out={work / 'set.pb'}", f"--python_out={work}",
                str(work / "greeter.proto"),
            ],
            check=True,
        )
        sys.path.insert(0, str(work))
        pb = importlib.import_module("greeter_pb2")
        request = pb.HelloRequest(
            name="Leo", tags=["a", "bcd"], nickname="", mood=pb.MOOD_GRUMPY,
            extras={"calls": 42, "zero": 0},
        )
        reply = pb.HelloReply(
            message="hello, ", calls=42, scores=[1, 3], ratio=0.5,
            badges=[pb.HelloReply.Badge(label="grumpy")],
        )
        vectors = {
            "protoc_set": (work / "set.pb").read_bytes(),
            "python_request": request.SerializeToString(deterministic=True),
            "python_reply": reply.SerializeToString(deterministic=True),
        }
    body = [
        "// Generated by scripts/gen_protoc_vectors.py from protoc and Python's protobuf",
        "// runtime. Do not edit; run the script again.",
    ]
    for name, data in vectors.items():
        body += ["", "///|", f'let {name} : String = "{data.hex()}"']
    body += [
        "",
        "///|",
        "fn nibble(c : UInt16) -> Int {",
        "  let n = c.to_int()",
        "  if n <= '9'.to_int() { n - '0'.to_int() } else { n - 'a'.to_int() + 10 }",
        "}",
        "",
        "///|",
        "fn unhex(text : String) -> Bytes {",
        "  Bytes::makei(text.length() / 2, i => {",
        "    ((nibble(text[2 * i]) << 4) | nibble(text[2 * i + 1])).to_byte()",
        "  })",
        "}",
        "",
        "///|",
        'test "protoc compiles the printed source back to the same descriptor" {',
        "  let files = @moonrpc.decode_file_descriptor_set(unhex(protoc_set))",
        "  assert_eq(files.length(), 1)",
        "  assert_eq(hex(files[0].encode()), hex(descriptor().encode()))",
        "  assert_true(files[0] == descriptor())",
        "}",
        "",
        "///|",
        'test "messages encode as Python\'s protobuf encodes them, and decode back" {',
        "  let request : HelloRequest = {",
        '    name: "Leo",',
        '    tags: ["a", "bcd"],',
        '    nickname: Some(""),',
        "    mood: Grumpy,",
        '    extras: { "calls": 42, "zero": 0 },',
        "  }",
        "  assert_eq(hex(@moonrpc.Message::encode(request)), python_request)",
        "  let back : HelloRequest = @moonrpc.Message::decode(unhex(python_request))",
        "  assert_eq(hex(@moonrpc.Message::encode(back)), python_request)",
        "  let reply : HelloReply = {",
        '    message: "hello, ",',
        "    calls: 42,",
        "    scores: [1, 3],",
        "    ratio: 0.5,",
        '    badges: [{ label: "grumpy" }],',
        "    cached: false,",
        "  }",
        "  assert_eq(hex(@moonrpc.Message::encode(reply)), python_reply)",
        "}",
    ]
    OUT.write_text("\n".join(body) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")


main()

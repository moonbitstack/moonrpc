#!/usr/bin/env python3
"""Turn the `.proto` files under `src/conformance/idl` into a MoonBit module.

MoonBit has no way to embed a file at build time, so the sources a service compiles at start-up
are written into a generated module. CI runs this and fails if the result differs, which is what
keeps the generated copy and the `.proto` files from drifting apart.
"""
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
IDL = ROOT / "src" / "conformance" / "idl"
OUT = ROOT / "src" / "conformance" / "idl.mbt"

# The name each file is known by, which is what an `import` in another file writes.
NAMES = {
    "config.proto": "connectrpc/conformance/v1/config.proto",
    "service.proto": "connectrpc/conformance/v1/service.proto",
    "any.proto": "google/protobuf/any.proto",
}


def literal(text: str) -> str:
    lines = text.rstrip("\n").split("\n")
    return "\n".join("    #|" + line for line in lines)


def main() -> None:
    parts = [
        "// Generated by `scripts/gen_conformance_idl.py` from `src/conformance/idl/*.proto`.",
        "// Do not edit: run the script instead.",
        "",
        "///|",
        "/// The `.proto` files the reference service is defined by, in the order they are handed to",
        "/// the compiler: a file may be imported before it appears here, because names resolve",
        "/// across the whole set.",
        "pub fn sources() -> Array[(String, String)] {",
        "  [",
    ]
    for name, known in NAMES.items():
        parts.append("    (\n      %s," % ('"' + known + '"'))
        parts.append(literal((IDL / name).read_text(encoding="utf-8")))
        parts.append("    ),")
    parts.append("  ]")
    parts.append("}")
    OUT.write_text("\n".join(parts) + "\n", encoding="utf-8", newline="\n")
    print("wrote", OUT.relative_to(ROOT))


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""Copy the schema of `src/examples/30-proto-source` into the package as text.

MoonBit has no way to embed a file at build time, so the example reads its `.proto` from a
generated MoonBit string. CI runs this and fails if the result differs, which is what keeps the
copy and the file from drifting apart.
"""
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
EXAMPLE = ROOT / "src" / "examples" / "30-proto-source"
SCHEMA = EXAMPLE / "greet.proto"
OUT = EXAMPLE / "greet_proto.mbt"


def literal(text: str) -> str:
    return "\n".join("    #|" + line for line in text.rstrip("\n").split("\n"))


def main() -> None:
    parts = [
        "// Generated by `scripts/gen_proto_source.py` from `greet.proto`. Do not edit: run the",
        "// script instead.",
        "",
        "///|",
        "/// `greet.proto` by the name a descriptor knows it by, and its text, which is what the",
        "/// example compiles at run time.",
        "pub fn proto_source() -> (String, String) {",
        "  let text =",
        literal(SCHEMA.read_text(encoding="utf-8")),
        '  ("greet.proto", text)',
        "}",
    ]
    OUT.write_text("\n".join(parts) + "\n", encoding="utf-8", newline="\n")
    print("wrote", OUT.relative_to(ROOT))


if __name__ == "__main__":
    main()
